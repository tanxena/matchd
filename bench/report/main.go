// Command report generates the README's benchmark tables from the result
// files benchrun wrote (PRD 7.8, decision 021): every number in the README
// comes from a committed file in bench/results, through this program.
//
//	report -results bench/results -readme README.md   # rewrite the README's benchmark section
//	report -results bin/bench-smoke -smoke -min-runs 1 -out report.md
//
// It refuses to report a configuration with fewer than -min-runs counted
// runs, or results with any disturbed or failed run, unless
// -allow-disturbed (they are then left out of the numbers and listed).
package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"os"
)

// The README section between these markers is generated.
const (
	beginMarker = "<!-- bench:begin: generated by bench/report from bench/results; do not edit by hand -->"
	endMarker   = "<!-- bench:end -->"
)

func main() {
	dir := flag.String("results", "bench/results", "directory of result files (searched recursively)")
	readme := flag.String("readme", "", "rewrite the generated section of this file")
	out := flag.String("out", "", "write the generated section to this file")
	allow := flag.Bool("allow-disturbed", false, "report even if some runs were disturbed or failed (they are left out and listed)")
	minRuns := flag.Int("min-runs", 5, "least counted runs per configuration (PRD 7.5)")
	smoke := flag.Bool("smoke", false, "checking the harness: count disturbed runs too, and say so at the top (never for the README)")
	flag.Parse()

	runs, err := load(*dir)
	if err != nil {
		fatal(err)
	}
	if *smoke && *readme != "" {
		fatal(errors.New("-smoke output never goes into the README"))
	}
	if err := check(groups(runs, *smoke), *minRuns, *allow || *smoke); err != nil {
		fatal(err)
	}
	section := render(runs, *smoke)
	switch {
	case *readme != "":
		if err := splice(*readme, section); err != nil {
			fatal(err)
		}
	case *out != "":
		if err := os.WriteFile(*out, []byte(section), 0o644); err != nil {
			fatal(err)
		}
	default:
		fmt.Print(section)
	}
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "report:", err)
	os.Exit(1)
}

// splice replaces what lies between the markers in path with section.
func splice(path, section string) error {
	b, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	i := bytes.Index(b, []byte(beginMarker))
	j := bytes.Index(b, []byte(endMarker))
	if i < 0 || j < i {
		return errors.New(path + ": no benchmark markers (" + beginMarker + " ... " + endMarker + ")")
	}
	var nb bytes.Buffer
	nb.Write(b[:i+len(beginMarker)])
	nb.WriteString("\n\n" + section + "\n")
	nb.Write(b[j:])
	return os.WriteFile(path, nb.Bytes(), 0o644)
}
